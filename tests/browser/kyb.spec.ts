import { test, expect, type Page } from '@playwright/test';
const sampleFile = { name: 'sample-evidence.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\nSample only\n%%EOF') };
const step = (page: Page, name: string) => page.getByRole('navigation', { name: 'KYB steps' }).getByRole('link', { name: new RegExp(name) });
test.skip(process.env.NEXT_PUBLIC_MONEY_STATION_DEMO_KYB==='1','Regular intake tests run against the default build; demo approval has its own browser cases.');
test('KYB pages preserve intake, validate evidence and prepare a request without claiming provider approval', async ({ page }, info) => {
  const errors: string[] = [], writes: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', request => { if (['POST','PUT','PATCH'].includes(request.method())) writes.push(request.url()); });
  await page.goto('/kyb/review/');
  await expect(page.getByRole('button', { name: 'Prepare KYB request', exact: true })).toBeDisabled();
  await step(page, 'Overview').click();
  await page.getByRole('button', { name: 'Use sample business details' }).click();
  await step(page, 'Business details').click();
  await expect(page.getByLabel('Legal business name')).toHaveValue('Meridian Studio Example Ltd');
  await expect(page.getByLabel('Registration jurisdiction')).toHaveValue('ADGM');
  await page.getByRole('button', { name: 'Continue to people' }).click();
  await page.getByLabel('Person 1 ownership percentage').fill('101');
  await page.getByRole('button', { name: 'Continue to documents' }).click();
  await expect(page.locator('.kyb-step-content').getByRole('alert')).toContainText('0–100%');
  await page.getByLabel('Person 1 ownership percentage').fill('75');
  await page.getByRole('button', { name: 'Add person', exact: true }).click();
  await page.getByLabel('Person 2 full name').fill('Sam Example');
  await page.getByLabel('Person 2 country of residence').fill('United States');
  await page.getByLabel('Person 2 ownership percentage').fill('25');
  await page.getByLabel('I have included the people').check();
  await page.screenshot({ path: info.outputPath('kyb-people.png'), fullPage: true });
  await page.getByRole('button', { name: 'Continue to documents' }).click();
  await page.getByLabel('Sample business registration document').setInputFiles({ name: 'invalid.txt', mimeType: 'text/plain', buffer: Buffer.from('sample') });
  await expect(page.locator('.kyb-step-content').getByRole('alert')).toContainText('matching file type');
  for (const title of ['business registration', 'registered business address', 'ownership & control record', 'authority to represent']) await page.getByLabel(`Sample ${title} document`, { exact: true }).setInputFiles(sampleFile);
  await expect(page.getByText('Selected for demo, not uploaded', { exact: false })).toHaveCount(4);
  await page.getByRole('button', { name: 'Review request', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Prepare KYB request', exact: true })).toBeDisabled();
  await page.getByLabel('Confirm review and authority').check();
  await page.screenshot({ path: info.outputPath('kyb-review.png'), fullPage: true });
  await page.getByRole('button', { name: 'Prepare KYB request', exact: true }).click();
  await expect(page.getByText('Ready for provider handoff', { exact: true })).toBeVisible();
  await expect(page.getByText('Not assigned', { exact: true })).toBeVisible();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export sample request' }).click();
  const file = await download, stream = await file.createReadStream();
  const chunks: Buffer[] = []; for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const packet = JSON.parse(Buffer.concat(chunks).toString());
  expect(packet.verified).toBe(false); expect(packet.credentialIssued).toBe(false);
  expect(packet.providerSubmission).toBe('not_sent'); expect(packet.documentContentsIncluded).toBe(false);
  expect(packet.draft.people).toHaveLength(2);
  await page.screenshot({ path: info.outputPath('kyb-status.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(await page.evaluate(() => innerWidth));
  await step(page, 'Business details').click();
  await page.getByLabel('Legal business name').fill('Updated Example Ltd');
  await step(page, 'Verification status').click();
  await expect(page.getByText('No prepared request yet', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Export sample request' })).toHaveCount(0);
  await step(page, 'Review & prepare').click();
  await expect(page.getByLabel('Confirm review and authority')).not.toBeChecked();
  expect(writes).toEqual([]); expect(errors).toEqual([]);
});
test('KYB jurisdiction changes clear stale evidence and leaving or reloading discards the in-memory draft', async ({ page, isMobile }) => {
  await page.goto('/kyb/');
  await page.getByRole('button', { name: 'Use sample business details' }).click();
  await step(page, 'Supporting documents').click();
  await page.getByLabel('Sample business registration document').setInputFiles(sampleFile);
  await step(page, 'Business details').click();
  await page.getByLabel('Registration jurisdiction').selectOption('US');
  await expect(page.getByLabel('State registration number', { exact: true })).toHaveValue('');
  await step(page, 'Supporting documents').click();
  await expect(page.getByText('0 / 5 selected', { exact: true })).toBeVisible();
  await step(page, 'Business details').click();
  await expect(page.getByLabel('Legal business name')).toHaveValue('Meridian Studio Example Ltd');
  if (isMobile) await page.getByLabel('Open merchant navigation').click();
  await page.getByRole('navigation', { name: isMobile ? 'Mobile merchant navigation' : 'Merchant navigation' }).getByRole('link', { name: 'Invoices', exact: true }).click();
  if (isMobile) await page.getByLabel('Open merchant navigation').click();
  await page.getByRole('navigation', { name: isMobile ? 'Mobile merchant navigation' : 'Merchant navigation' }).getByRole('link', { name: 'Business verification', exact: true }).click();
  await step(page, 'Business details').click();
  await expect(page.getByLabel('Legal business name')).toHaveValue('');
  await step(page, 'Overview').click();
  await page.getByRole('button', { name: 'Use sample business details' }).click();
  await step(page, 'Business details').click();
  await expect(page).toHaveURL(/\/kyb\/business\/$/);
  await expect(page.getByLabel('Legal business name')).toHaveValue('Meridian Studio Example Ltd');
  await page.reload();
  await expect(page.getByLabel('Legal business name')).toHaveValue('');
  await expect(page.getByLabel('Registration jurisdiction')).toHaveValue('');
  await step(page, 'Verification status').click();
  await expect(page.getByText('No prepared request yet', { exact: true })).toBeVisible();
});
